#!/usr/bin/env node
// Regenerates data/index.json.
//
// The web app is served as a static site, so the browser cannot enumerate the
// data/ directory on its own. This manifest gives the "打开" dialog the list of
// project mind maps that ship with the site.
//
// Run after adding or removing a file in data/:
//   npm run data:index

import { readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = path.join(root, "data");
const manifestName = "index.json";

const files = [];
for (const name of await readdir(dataDir)) {
  if (!/\.json$/i.test(name) || name === manifestName) continue;
  const info = await stat(path.join(dataDir, name));
  if (!info.isFile()) continue;
  files.push({ name, size: info.size, mtime: Math.round(info.mtimeMs) });
}

files.sort((left, right) => left.name.localeCompare(right.name, "zh-CN"));

const manifest = {
  generatedAt: new Date().toISOString(),
  note: "Generated by tools/build-data-index.mjs - do not edit by hand.",
  files,
};

const target = path.join(dataDir, manifestName);
await writeFile(target, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");

console.log(`data/${manifestName}: ${files.length} projects`);
for (const file of files) {
  console.log(`  ${(file.size / 1024).toFixed(0).padStart(8)} KB  ${file.name}`);
}
